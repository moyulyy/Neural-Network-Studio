@lru_cache(maxsize=256)
def icon(name: str, color: str, size: int = 18) -> QIcon:
    path = _PATHS.get(name, _PATHS["grid"])
    svg = (
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" '
        f'stroke="{color}" stroke-width="1.8" stroke-linecap="round" '
        f'stroke-linejoin="round">{path}</svg>'
    )
    renderer = QSvgRenderer(QByteArray(svg.encode("utf-8")))
    scale = 2
    pixmap = QPixmap(size * scale, size * scale)
    pixmap.fill(Qt.GlobalColor.transparent)
    painter = QPainter(pixmap)
    painter.setRenderHint(QPainter.RenderHint.Antialiasing, True)
    renderer.render(painter)
    painter.end()
    pixmap.setDevicePixelRatio(scale)
    return QIcon(pixmap)


def icon_pixmap(name: str, color: str, size: int = 18) -> QPixmap:
    return icon(name, color, size).pixmap(QSize(size, size))


def set_button_icon(button, name: str, color: str, size: int = 16) -> None:
    button.setIcon(icon(name, color, size))
    button.setIconSize(QSize(size, size))
    setattr(button, "_icon_name", name)
    setattr(button, "_icon_size", size)
